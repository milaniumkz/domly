import 'dart:convert';
import 'dart:io';
import 'package:crypto/crypto.dart';
import 'package:analyzer/dart/analysis/utilities.dart';
import 'inventory.dart';
import '../../lib/localization/kazakh_translations.dart';
import '../../lib/localization/builtin_translations.dart';

String quoted(String s) => jsonEncode(s).replaceAll(r'$', r'\$');
String sql(String s) => "'${s.replaceAll("'", "''")}'";
void main() {
  final rows = <Map<String, dynamic>>[];
  for (final f
      in Directory('lib')
          .listSync(recursive: true)
          .whereType<File>()
          .where(
            (f) =>
                f.path.endsWith('.dart') &&
                !f.path.contains('/localization/') &&
                !f.path.contains('/admin'),
          )) {
    final s = f.readAsStringSync();
    parseString(
      content: s,
      throwIfDiagnostics: false,
    ).unit.accept(Inventory(f.path, s, rows));
  }
  final entries = <String, Set<String>>{};
  for (final r in rows) {
    final s = (r['text'] as String).replaceAll(RegExp(r'\s+'), ' ').trim();
    if (s.length < 2 ||
        s.startsWith('<!doctype') ||
        s.startsWith('^') ||
        ['астана', 'нурсултан'].contains(s))
      continue;
    (entries[s] ??= <String>{}).add(r['file'] as String);
  }
  final sources = entries.keys.toList()..sort();
  File('lib/localization/default_translation_sources.dart').writeAsStringSync(
    '// Generated by tool/ui_texts/generate.dart. Do not edit.\nconst kDefaultTranslationSources = <String>[\n${sources.map((s) => '  ${quoted(s)},').join('\n')}\n];\n',
  );
  final manifest = [
    for (final s in sources)
      {
        'key': 't_${sha1.convert(utf8.encode(s)).toString().substring(0, 16)}',
        'source': s,
        'locations': entries[s]!.toList()..sort(),
      },
  ];
  File('backend/sql/ui_text_catalog.sql').writeAsStringSync(
    '-- Generated UI source catalogue. Existing administrator wording is preserved.\nINSERT INTO translations (key,ru,kk,source,locations) VALUES\n${manifest.map((r) => '(${sql(r['key'] as String)},${sql(r['source'] as String)},${sql(kBuiltinTranslations[r['source']]?['kk'] ?? kKazakhTranslations[r['source']] ?? '')},${sql(r['source'] as String)},${sql(jsonEncode(r['locations']))}::jsonb)').join(',\n')}\nON CONFLICT (key) DO UPDATE SET source=EXCLUDED.source, locations=EXCLUDED.locations, kk=COALESCE(NULLIF(btrim(translations.kk),\'\'), EXCLUDED.kk);\n',
  );
  File('tool/ui_texts/catalog.json').writeAsStringSync(
    '${const JsonEncoder.withIndent('  ').convert(manifest)}\n',
  );
  stdout.writeln('${sources.length} source texts');
}
